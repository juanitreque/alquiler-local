<div class="tarjeta">
  <strong>Factura cada mes</strong>
  <p>El alquiler de un local lleva IVA del 21 %; solo la vivienda está exenta. Hay que hacer factura cada mes y, si el inquilino es empresa o autónomo,
    expedirla antes del día 16 del mes siguiente. La numeración es correlativa por año. Una factura emitida no se borra: se corrige con una rectificativa.</p>
</div>
<div class="tarjeta">
  <strong>Retención del 19 %</strong>
  <p>Si el inquilino es empresa o autónomo, descuenta un 19 % de la base y lo ingresa él en Hacienda (modelos 115 y 180).
    El propietario no presenta nada por eso: las retenciones se restan en su Renta. No hay retención si el inquilino es un particular.</p>
</div>
<div class="tarjeta">
  <strong>IVA: modelo 303 cada trimestre</strong>
  <p>Del 1 al 20 de abril, julio y octubre, y hasta el 30 de enero. Quien solo alquila locales no presenta el resumen anual 390,
    pero en el 303 del 4T hay que rellenar el apartado de información anual (epígrafe 861.2).
    Si la retención la practica el inquilino, el alquiler tampoco va en el modelo 347.</p>
</div>
<div class="tarjeta">
  <strong>Renta</strong>
  <p>Son rendimientos del capital inmobiliario, no una actividad económica. Por eso no hay que presentar el modelo 130 ni darse de alta en autónomos (RETA),
    y si el propietario cobra una pensión de jubilación, no se ve afectada. En un local no se aplica la reducción del 60 % de las viviendas.</p>
</div>
<div class="tarjeta">
  <strong>VeriFactu no aplica</strong>
  <p>El reglamento de sistemas de facturación (RD 1007/2023) obliga a quienes tienen actividad económica. Una persona física que alquila un local
    sin empleado obtiene rendimientos del capital inmobiliario y no está obligada. Si algún año contratara a alguien a jornada completa para el alquiler, cambiaría.</p>
</div>
<div class="tarjeta">
  <strong>Fianza en el IBAVI</strong>
  <p>En Baleares, la fianza (2 mensualidades en locales) se deposita en el Institut Balear de l'Habitatge en 30 días (Ley 5/2018). No depositarla se multa.</p>
</div>
<div class="tarjeta">
  <strong>Copropiedad</strong>
  <p>Si el local es ganancial, puede facturar solo el cónyuge que figura como arrendador, y en la Renta se reparte al 50 %.
    Si es de los dos en proindiviso (separación de bienes), Hacienda lo trata como comunidad de bienes con su propio NIF. Confírmalo con el gestor.</p>
</div>
<div class="tarjeta">
  <strong>Conservación</strong>
  <p>Hay que guardar facturas y libros registro al menos 4 años (6 años es lo prudente). Haz copias de seguridad.</p>
</div>
<p class="nota">Información general revisada en octubre de 2026. Ante cualquier cambio de situación, consulta con un asesor fiscal.</p>
